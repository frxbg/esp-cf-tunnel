type logger struct{}

func (logger) Infof(context.Context, string, ...interface{})  {}
func (logger) Errorf(context.Context, string, ...interface{}) {}
func serve() {
	s := new(testServer)
	conn := rpc.NewConn(rpc.StreamTransport(stdio{}), rpc.MainInterface(proto.RegistrationServer_ServerToClient(s).Client), rpc.ConnLog(logger{}))
	select {
	case <-conn.Done():
	case <-time.After(15 * time.Second):
		_ = conn.Close()
		panic("RPC conversation timed out")
	}
	if !s.registered.Load() || !s.unregistered.Load() {
		panic("incomplete RPC conversation")
	}
	fmt.Fprintln(os.Stderr, "PASS: official Go RPC server decoded and executed registration and unregister")
}

func inspect(dir string) {
	for _, name := range []string{"bootstrap", "register", "finish_bootstrap", "finish_register", "unregister", "finish_unregister", "release"} {
		data, err := os.ReadFile(filepath.Join(dir, name+".bin"))
		must(err)
		msg, err := capnp.Unmarshal(data)
		must(err)
		root, err := wire.ReadRootMessage(msg)
		must(err)
		switch name {
		case "bootstrap":
			b, err := root.Bootstrap()
			must(err)
			must(require(b.QuestionId() == 0, "bootstrap question"))
		case "register", "unregister":
			c, err := root.Call()
			must(err)
			must(require(c.InterfaceId() == proto.RegistrationServer_TypeID, "interface ID"))
			t, err := c.Target()
			must(err)
			must(require(t.ImportedCap() == 37, "imported capability"))
			must(require(c.SendResultsTo().Which() == wire.Call_sendResultsTo_Which_caller, "result routing"))
			if name == "register" {
				must(require(c.QuestionId() == 1 && c.MethodId() == 0, "registration method"))
				payload, err := c.Params()
				must(err)
				ptr, err := payload.ContentPtr()
				must(err)
				params := proto.RegistrationServer_registerConnection_Params{Struct: ptr.Struct()}
				auth, err := params.Auth()
				must(err)
				secret, err := auth.TunnelSecret()
				must(err)
				must(require(bytes.Equal(secret, pattern(36)), "encoded 36-byte secret"))
			} else {
				must(require(c.QuestionId() == 2 && c.MethodId() == 1, "unregister method"))
			}
		case "release":
			r, err := root.Release()
			must(err)
			must(require(r.Id() == 37 && r.ReferenceCount() == 1, "release refcount"))
		default:
			f, err := root.Finish()
			must(err)
			id := uint32(0)
			if name == "finish_register" {
				id = 1
			}
			if name == "finish_unregister" {
				id = 2
			}
			must(require(f.QuestionId() == id && f.ReleaseResultCaps() == (id != 0), "finish lifecycle"))
		}
	}
	fmt.Println("PASS: official Go codec inspected all seven C message types")
}
func main() {
	defer func() {
		if e := recover(); e != nil {
			fmt.Fprintln(os.Stderr, e)
			os.Exit(1)
		}
	}()
	if len(os.Args) < 2 {
		panic("use generate DIR, inspect DIR, or serve")
	}
	switch os.Args[1] {
	case "generate":
		generate(os.Args[2])
	case "inspect":
		inspect(os.Args[2])
	case "serve":
		serve()
	default:
		panic(io.EOF)
	}
}
